def render_html(result: ScanResult) -> str:
    summary = result.summary()
    cards = "".join(
        f'<div class="card"><small>{key}</small><b style="color:{SEVERITY_COLOR.get(key, "#e6edf3")}">{summary[key]}</b></div>'
        for key in ("critical", "high", "medium", "low", "info", "total")
        if key in summary
    )
    blocks = []
    for finding in result.findings:
        blocks.append(
            "<finding class='{sev}'><span class='sev {sev}'>{sev}</span>"
            "<h3>{title}</h3><div class='tags'><span>{category}</span><span>confidence: {conf}</span>"
            "<span>{cwe}</span><span>cvss: {cvss}</span></div>"
            "<p>{detail}</p>{evidence}{remediation}{refs}</finding>".format(
                sev=html.escape(finding.severity),
                title=html.escape(finding.title),
                category=html.escape(finding.category or "-"),
                conf=html.escape(finding.confidence),
                cwe=html.escape(finding.cwe or "no CWE"),
                cvss=html.escape(str(finding.cvss or "-")),
                detail=html.escape(finding.detail),
                evidence=(f"<pre>{html.escape(finding.evidence)}</pre>" if finding.evidence else ""),
                remediation=(f"<p><b>Remediation:</b> {html.escape(finding.remediation)}</p>" if finding.remediation else ""),
                refs=(
                    "<p class='muted'>References: "
                    + " · ".join(
                        f'<a href="{html.escape(url)}" rel="noreferrer" target="_blank">{html.escape(url)}</a>'
                        for url in finding.references
                    )
                    + "</p>"
                    if finding.references
                    else ""
                ),
            )
        )
    if not blocks:
        blocks.append("<p class='muted'>No findings from the configured checks. This is not proof that the target is secure.</p>")
    errors = ""
    if result.errors:
        errors = "<h2>Limitations</h2><pre>" + html.escape("\n".join(result.errors)) + "</pre>"
    return HTML_TEMPLATE.format(
        title=f"{config.APP_NAME} report - {html.escape(result.target)}",
        app=config.APP_NAME,
        version=config.VERSION,
        generated=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        target=html.escape(result.target),
        kind=html.escape(result.kind),
        profile=html.escape(result.profile),
        scan_id=html.escape(result.scan_id),
        started=html.escape(result.started_at),
        finished=html.escape(result.finished_at or "-"),
        requests=result.requests_made or result.metadata.get("requests_made", 0),
        authorization=html.escape(result.authorization.get("reason", "not recorded")),
        risk=result.risk_score,
        cards=cards,
        total=summary["total"],
        findings="".join(blocks),
        observations=html.escape(json.dumps(result.observations_as_list(), indent=2)[:60000]),
        errors=errors,
    )


# ---------------------------------------------------------------------------- PDF
def render_pdf(result: ScanResult, path: Path) -> Path:
    from .pdf import build_report_pdf

    build_report_pdf(result, path)
    return path


def csv_rows(result: ScanResult) -> str:
    """Flat CSV of findings for spreadsheets."""
    import csv
    import io

    buffer = io.StringIO()
    writer = csv.writer(buffer)
    writer.writerow(["severity", "title", "category", "confidence", "location", "cwe", "cvss", "detail"])
    for finding in result.findings:
        writer.writerow(
            [finding.severity, finding.title, finding.category, finding.confidence, finding.location, finding.cwe, finding.cvss, finding.detail]
        )
    return buffer.getvalue()
