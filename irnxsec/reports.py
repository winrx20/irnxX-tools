"""Report writers: JSON, Markdown, standalone HTML and PDF.

Reports are self-contained artefacts: the HTML embeds its own CSS with no external
references, and the PDF is generated with reportlab when available, falling back to a
minimal built-in PDF writer otherwise.
"""
from __future__ import annotations

import html
import json
import re
from datetime import datetime, timezone
from pathlib import Path

from . import config
from .models import SEVERITY_ORDER, ScanResult

SEVERITY_COLOR = {
    "critical": "#ff2d55",
    "high": "#ff6b3d",
    "medium": "#ffc93c",
    "low": "#4db8ff",
    "info": "#8b97a8",
}


def _stem(result: ScanResult) -> str:
    safe = re.sub(r"[^a-zA-Z0-9.-]+", "_", result.target.replace("://", "_"))[:60] or "target"
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    return f"{stamp}_{result.kind}_{safe}_{result.scan_id}"


def write_reports(result: ScanResult) -> dict[str, str]:
    out = config.reports_dir()
    stem = _stem(result)
    paths = {
        "json": out / f"{stem}.json",
        "markdown": out / f"{stem}.md",
        "html": out / f"{stem}.html",
        "pdf": out / f"{stem}.pdf",
    }
    payload = result.to_dict()
    payload["generated_at"] = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    paths["json"].write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    paths["markdown"].write_text(render_markdown(result), encoding="utf-8")
    paths["html"].write_text(render_html(result), encoding="utf-8")
    try:
        render_pdf(result, paths["pdf"])
        written = {k: str(v) for k, v in paths.items() if v.exists()}
    except Exception as exc:
        paths["pdf"].unlink(missing_ok=True)
        written = {k: str(v) for k, v in paths.items() if v.exists()}
        written["pdf_error"] = str(exc)
    return written


# ----------------------------------------------------------------------- markdown
def render_markdown(result: ScanResult) -> str:
    summary = result.summary()
    lines = [
        f"# {config.APP_NAME} assessment report",
        "",
        f"- **Target:** `{result.target}`",
        f"- **Assessment kind:** {result.kind}",
        f"- **Profile:** {result.profile}",
        f"- **Scan ID:** `{result.scan_id}`",
        f"- **Started (UTC):** {result.started_at}",
        f"- **Finished (UTC):** {result.finished_at or '-'}",
        f"- **Requests made:** {result.requests_made or result.metadata.get('requests_made', 0)}",
        f"- **Risk score:** {result.risk_score}/100",
        f"- **Authorization:** {result.authorization.get('reason', 'not recorded')}",
        "",
        "## Severity summary",
        "",
        "| Severity | Count |",
        "| --- | --- |",
    ]
    for key in ("critical", "high", "medium", "low", "info"):
        lines.append(f"| {key.capitalize()} | {summary[key]} |")
    lines.extend([f"| **Total** | **{summary['total']}** |", "", "## Findings", ""])
    if not result.findings:
        lines.append("_No findings from the configured checks. This does not prove the target is secure._")
    for index, finding in enumerate(result.findings, start=1):
        lines.extend(
            [
                f"### {index}. [{finding.severity.upper()}] {finding.title}",
                "",
                f"- Category: {finding.category}",
                f"- Confidence: {finding.confidence}",
                f"- Location: `{finding.location or '-'}`",
                f"- CWE: {finding.cwe or '-'}",
                f"- CVSS: {finding.cvss or '-'}",
                "",
                finding.detail or "",
                "",
            ]
        )
        if finding.evidence:
            lines.extend(["**Evidence**", "", "```text", finding.evidence.replace("```", "'''"), "```", ""])
        if finding.remediation:
            lines.extend([f"**Remediation:** {finding.remediation}", ""])
        if finding.references:
            lines.append("**References:** " + ", ".join(finding.references))
            lines.append("")
    lines.extend(["## Observations", "", "```json", json.dumps(result.observations_as_list(), indent=2)[:60000], "```"])
    if result.errors:
        lines.extend(["", "## Limitations and errors", ""] + [f"- {e}" for e in result.errors])
    lines.extend(
        [
            "",
            "---",
            "",
            f"Generated by {config.APP_NAME} {config.VERSION} on a localhost-only installation.",
            "Automated checks are indicative: validate each finding manually before remediation or disclosure.",
        ]
    )
    return "\n".join(lines)


